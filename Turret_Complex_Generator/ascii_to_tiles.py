# ascii_to_tiles.py
import json
import sys
from pathlib import Path

if len(sys.argv) != 4:
    sys.exit("Usage : python ascii_to_tiles.py grille.txt legende.json tiles.json")

_, grid_arg, legend_arg, output_arg = sys.argv
grid_path, legend_path, output_path = map(Path, (grid_arg, legend_arg, output_arg))

try:
    rows = grid_path.read_text(encoding="utf-8").splitlines()
    legend = json.loads(legend_path.read_text(encoding="utf-8"))
except OSError as exc:
    sys.exit(f"Erreur de lecture : {exc}")
except json.JSONDecodeError as exc:
    sys.exit(f"JSON de légende invalide : {exc}")

while rows and next(iter(rows)) == "":
    rows.pop(0)
while rows and next(reversed(rows)) == "":
    rows.pop()

if not rows:
    sys.exit("Erreur : grille vide.")

width  = len(next(iter(rows)))
height = len(rows)

if width == 0 or any(len(row) != width for row in rows):
    sys.exit("Erreur : la grille doit être rectangulaire et sans lignes vides.")

allowed = set(legend) | {"*", " "}
unknown = sorted({ch for row in rows for ch in row if ch not in allowed})
if unknown:
    sys.exit(f"Erreur : caractères absents de la légende : {unknown!r}")

grid_names = [["air" for _ in range(width)] for _ in range(height)]
blocks = {"air": {"id": "air"}}
covered = set()
bridge_positions = []

for y, row in enumerate(rows):
    for x, char in enumerate(row):
        if char in (" ", "*"):
            continue
        entry = legend.get(char)
        if isinstance(entry, str):
            entry = {"id": entry}
        block_id = entry.get("id", "air")
        if block_id == "air":
            continue

        rotation = entry.get("rotation", 0)
        w_bloc   = entry.get("width",  1)
        h_bloc   = entry.get("height", 1)
        cfg      = entry.get("config", None)

        suffix_r = f"_r{rotation}" if rotation != 0 else ""
        suffix_c = f"_{cfg}" if cfg else ""
        name = f"{block_id}{suffix_r}{suffix_c}"

        if "bridge" in block_id or block_id in ("phase-conveyor", "phase-conduit"):
            bridge_positions.append((x, y, block_id, rotation))

        if name not in blocks:
            b_def = {"id": block_id, "rotation": rotation}
            if cfg:
                b_def.update({"config": {"type": "item", "value": cfg}})
            blocks.update({name: b_def})

        for dy in range(h_bloc):
            for dx in range(w_bloc):
                px, py = x + dx, y + dy
                if px >= width or py >= height:
                    sys.exit(f"Erreur : l'empreinte de {char!r} en ({x},{y}) dépasse la grille.")
                if (px, py) in covered:
                    sys.exit(f"Erreur : chevauchement en ({px},{py}).")
                covered.add((px, py))

        cx = x + (w_bloc - 1) // 2
        cy = y + (h_bloc // 2)
        grid_names[cy][cx] = name

def cle_x(b):
    x, y, bid, rot = b
    return x

def cle_y(b):
    x, y, bid, rot = b
    return y

def relier_pont(x_in, y_in, bid_in, rot_in, x_out, y_out):
    dx_link = x_out - x_in
    dy_link = y_in - y_out
    name_in = f"{bid_in}_r{rot_in}_dx{dx_link}_dy{dy_link}"
    blocks.update({
        name_in: {
            "id": bid_in,
            "rotation": rot_in,
            "config": {"type": "point", "value": f"{dx_link}, {dy_link}"}
        }
    })
    grid_names[y_in][x_in] = name_in

# 1. Paires verticales (rotation 1 : bas -> haut, ou rotation 3 : haut -> bas)
par_colonne = {}
for b in bridge_positions:
    x, y, bid, rot = b
    if rot in (1, 3):
        par_colonne.setdefault((x, bid, rot), []).append(b)

for (x, bid, rot), liste_b in par_colonne.items():
    liste_b.sort(key=cle_y, reverse=(rot == 1))
    it = iter(liste_b)
    for b1 in it:
        b2 = next(it, None)
        if b2 is None:
            break
        x1, y1, bid1, rot1 = b1
        x2, y2, _, _ = b2
        if 1 <= abs(y1 - y2) <= 6:
            relier_pont(x1, y1, bid1, rot1, x2, y2)

# 2. Paires horizontales dans les couloirs (rotation 2 : droite -> gauche, ou rotation 0 : gauche -> droite)
par_ligne = {}
for b in bridge_positions:
    x, y, bid, rot = b
    if rot in (0, 2):
        par_ligne.setdefault((y, bid, rot), []).append(b)

for (y, bid, rot), liste_b in par_ligne.items():
    liste_b.sort(key=cle_x, reverse=(rot == 2))
    it = iter(liste_b)
    for b1 in it:
        b2 = next(it, None)
        if b2 is None:
            break
        x1, y1, bid1, rot1 = b1
        x2, y2, _, _ = b2
        if 1 <= abs(x1 - x2) <= 4:
            relier_pont(x1, y1, bid1, rot1, x2, y2)

output = {
    "$schema": "https://githubusercontent.com",
    "info": {"name": "turret_complex", "description": "Generated by turret_complex.py", "authors": ["turret_complex"], "version": "1.0.0"},
    "tiles": {"grid": grid_names, "blocks": blocks, "programs": {}},
    "consts": {}
}

output_path.write_text(json.dumps(output, indent=2, ensure_ascii=True), encoding="utf-8")
print(f"Description créée : {output_path}")
